package org.bukkit.boss;

/**
 * @since 1.9.4
 */
public enum BarFlag {

    /**
     * Darkens the sky like during fighting a wither.
     *
     * @since 1.9.4
     */
    DARKEN_SKY,
    /**
     * Tells the client to play the Ender Dragon boss music.
     *
     * @since 1.9.4
     */
    PLAY_BOSS_MUSIC,
    /**
     * Creates fog around the world.
     *
     * @since 1.9.4
     */
    CREATE_FOG,
}
