package org.bukkit.block;

/**
 * Represents the face and the direction of a block
 *
 * @since 1.21.6
 */
public enum Orientation {

    /**
     * @since 1.21.6
     */
    DOWN_EAST,
    /**
     * @since 1.21.6
     */
    DOWN_NORTH,
    /**
     * @since 1.21.6
     */
    DOWN_SOUTH,
    /**
     * @since 1.21.6
     */
    DOWN_WEST,
    /**
     * @since 1.21.6
     */
    UP_EAST,
    /**
     * @since 1.21.6
     */
    UP_NORTH,
    /**
     * @since 1.21.6
     */
    UP_SOUTH,
    /**
     * @since 1.21.6
     */
    UP_WEST,
    /**
     * @since 1.21.6
     */
    WEST_UP,
    /**
     * @since 1.21.6
     */
    EAST_UP,
    /**
     * @since 1.21.6
     */
    NORTH_UP,
    /**
     * @since 1.21.6
     */
    SOUTH_UP
}
