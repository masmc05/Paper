package org.bukkit;

/**
 * Tree and organic structure types.
 *
 * @since 1.0.0
 */
public enum TreeType {

    /**
     * Regular tree, no branches
     *
     * @since 1.0.0
     */
    TREE,
    /**
     * Regular tree, extra tall with branches
     *
     * @since 1.0.0
     */
    BIG_TREE,
    /**
     * Redwood tree, shaped like a pine tree
     *
     * @since 1.0.0
     */
    REDWOOD,
    /**
     * Tall redwood tree with just a few leaves at the top
     *
     * @since 1.0.0
     */
    TALL_REDWOOD,
    /**
     * Birch tree
     *
     * @since 1.0.0
     */
    BIRCH,
    /**
     * Standard jungle tree; 4 blocks wide and tall
     *
     * @since 1.2.2
     */
    JUNGLE,
    /**
     * Smaller jungle tree; 1 block wide
     *
     * @since 1.3.1
     */
    SMALL_JUNGLE,
    /**
     * Jungle tree with cocoa plants; 1 block wide
     *
     * @since 1.7.10
     */
    COCOA_TREE,
    /**
     * Small bush that grows in the jungle
     *
     * @since 1.3.1
     */
    JUNGLE_BUSH,
    /**
     * Big red mushroom; short and fat
     *
     * @since 1.1.0
     */
    RED_MUSHROOM,
    /**
     * Big brown mushroom; tall and umbrella-like
     *
     * @since 1.1.0
     */
    BROWN_MUSHROOM,
    /**
     * Swamp tree (regular with vines on the side)
     *
     * @since 1.3.1
     */
    SWAMP,
    /**
     * Acacia tree.
     *
     * @since 1.7.2
     */
    ACACIA,
    /**
     * Dark Oak tree.
     *
     * @since 1.7.2
     */
    DARK_OAK,
    /**
     * Mega redwood tree; 4 blocks wide and tall
     *
     * @since 1.7.2
     */
    MEGA_REDWOOD,
    /**
     * Mega pine tree
     *
     * @since 1.20.6
     */
    MEGA_PINE,
    /**
     * Tall birch tree
     *
     * @since 1.7.2
     */
    TALL_BIRCH,
    /**
     * Large plant native to The End
     *
     * @since 1.9.4
     */
    CHORUS_PLANT,
    /**
     * Large crimson fungus native to the nether
     *
     * @since 1.16.1
     */
    CRIMSON_FUNGUS,
    /**
     * Large warped fungus native to the nether
     *
     * @since 1.16.1
     */
    WARPED_FUNGUS,
    /**
     * Tree with large roots which grows above lush caves
     *
     * @since 1.17
     */
    AZALEA,
    /**
     * Mangrove tree
     *
     * @since 1.19
     */
    MANGROVE,
    /**
     * Tall mangrove tree
     *
     * @since 1.19
     */
    TALL_MANGROVE,
    /**
     * Cherry tree
     *
     * @since 1.19.4
     */
    CHERRY,
    /**
     * Pale oak tree
     *
     * @since 1.21.3
     */
    PALE_OAK,
    /**
     * Pale oak tree with a creaking heart
     *
     * @since 1.21.3
     */
    PALE_OAK_CREAKING,
}
