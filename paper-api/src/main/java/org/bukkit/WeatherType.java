package org.bukkit;

/**
 * An enum of all current weather types
 *
 * @since 1.5.1
 */
public enum WeatherType {

    /**
     * Raining or snowing depending on biome.
     *
     * @since 1.5.1
     */
    DOWNFALL,
    /**
     * Clear weather, clouds but no rain.
     *
     * @since 1.5.1
     */
    CLEAR,
    ;
}
